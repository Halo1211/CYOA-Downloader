"""Generate docs/THIRD_PARTY_NOTICES.md from `cargo metadata --locked`.

Lists every crate in the normal (non-dev, non-build) dependency graph of the
workspace binaries for the host target, with its declared SPDX license.
Run from the repo root: python scripts/third_party_notices.py

With `--bundle DIR`, also copies every crate's license/notice files into
DIR/<crate>-<version>/ (plus font licenses shipped inside crates, e.g. the egui
default fonts' OFL/UFL texts). If a crate omits its license file, the bundle
uses a license text with the same SPDX identifier from another dependency and
records the source. Packaging fails if no matching text is available.
"""

import json
import shutil
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
meta = json.loads(
    subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", "x86_64-pc-windows-msvc"],
        cwd=ROOT, stdout=subprocess.PIPE, check=True,
    ).stdout
)
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
members = set(meta["workspace_members"])

seen, stack = set(), list(members)
while stack:
    pid = stack.pop()
    if pid in seen:
        continue
    seen.add(pid)
    for dep in nodes[pid]["deps"]:
        kinds = {k["kind"] for k in dep["dep_kinds"]}
        if None in kinds:  # normal dependency
            stack.append(dep["pkg"])

rows = sorted(
    (pkgs[p]["name"], pkgs[p]["version"], pkgs[p].get("license") or "UNKNOWN (check crate)")
    for p in seen - members
)
counts = Counter(lic for _, _, lic in rows)
lines = [
    "# Third-party notices (Rust port)",
    "",
    "Generated by `scripts/third_party_notices.py` from `cargo metadata` "
    "(normal dependencies of the workspace binaries, target x86_64-pc-windows-msvc). "
    "Each crate is distributed under the license(s) shown; full texts are in each "
    "crate's source package. Review entries marked UNKNOWN before publishing.",
    "",
    f"Crates: {len(rows)}",
    "",
    "## License summary",
    "",
    "| License expression | Crates |",
    "|---|---|",
    *[f"| {lic} | {n} |" for lic, n in counts.most_common()],
    "",
    "## Crates",
    "",
    "| Crate | Version | License |",
    "|---|---|---|",
    *[f"| {n} | {v} | {lic} |" for n, v, lic in rows],
    "",
    # Kept in the generator so regeneration never drops it.
    "## Release obligations (reviewed by maintainers, not legal advice)",
    "- **MPL-2.0** (`cssparser`, `cssparser-macros`, `dtoa-short`, `selectors`): file-level "
    "copyleft. The binaries may be distributed under any terms. Unmodified, so no source "
    "changes need to be published. Include the MPL-2.0 text and a link to the upstream source.",
    "- **`epaint_default_fonts`** (bundled into `cyoa-desktop.exe`): the fonts are under "
    "OFL-1.1 and the Ubuntu Font Licence 1.0. Include both licence texts in the distribution "
    "(`--bundle` copies them from the crate's `fonts/` folder).",
    "- **`self_cell`**: dual-licensed \"Apache-2.0 OR GPL-2.0-only\"; use it under Apache-2.0.",
    "- Everything else uses permissive licences (MIT, Apache-2.0, BSD, ISC, Zlib, Unicode-3.0, "
    "Unlicense, CC0, BSL-1.0). Keep their copyright notices in the distribution's license bundle.",
    "- Build the bundle with `python scripts/third_party_notices.py --bundle <dist>/LICENSES`. "
    "For crates that omit license files, matching SPDX text is copied from serde (MIT/Apache-2.0), "
    "alloc-no-stdlib (BSD-3-Clause), or cssparser (MPL-2.0), with source notes in each crate folder. "
    "Packaging fails if no matching license text can be found.",
    "",
]
out = ROOT / "docs" / "THIRD_PARTY_NOTICES.md"
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out} ({len(rows)} crates)", file=sys.stderr)
for lic, n in counts.most_common():
    print(f"{n:4d}  {lic}", file=sys.stderr)

LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")


def license_files(crate_dir: Path) -> list[Path]:
    found = [f for f in crate_dir.iterdir()
             if f.is_file() and f.name.upper().startswith(LICENSE_PREFIXES)]
    fonts = crate_dir / "fonts"
    if fonts.is_dir():  # font licenses (OFL/UFL/...) ship next to the fonts
        found += [f for f in fonts.iterdir() if f.is_file() and f.suffix.lower() == ".txt"]
    return sorted(found)
LICENSE_FALLBACKS = {
    "MIT OR Apache-2.0": ("serde", ("APACHE", "MIT")),
    "BSD-3-Clause": ("alloc-no-stdlib", ()),
    "MPL-2.0": ("cssparser", ()),
}
PKGS_BY_NAME = {pkg["name"]: pkg for pkg in pkgs.values()}


def fallback_license_files(pkg: dict) -> tuple[str, list[Path]] | None:
    expression = pkg.get("license") or ""
    for identifier, (source_name, required_markers) in LICENSE_FALLBACKS.items():
        if expression != identifier:
            continue
        source_pkg = PKGS_BY_NAME.get(source_name)
        if source_pkg is None:
            return None
        source_dir = Path(source_pkg["manifest_path"]).parent
        files = license_files(source_dir)
        if required_markers:
            files = [f for f in files if any(marker in f.name.upper() for marker in required_markers)]
        if files:
            return source_name, files
    return None

if "--bundle" in sys.argv:
    dest = Path(sys.argv[sys.argv.index("--bundle") + 1]).resolve()
    if dest.exists():
        sys.exit(f"refusing to overwrite existing {dest}")
    dest.mkdir(parents=True)
    stubs = []
    for pid in sorted(seen - members, key=lambda p: (pkgs[p]["name"], pkgs[p]["version"])):
        pkg = pkgs[pid]
        out = dest / f"{pkg['name']}-{pkg['version']}"
        out.mkdir()
        files = license_files(Path(pkg["manifest_path"]).parent)
        for f in files:
            rel = f.relative_to(Path(pkg["manifest_path"]).parent)
            target = out / str(rel).replace("\\", "_").replace("/", "_")
            shutil.copyfile(f, target)
        if not files:
            fallback = fallback_license_files(pkg)
            if fallback:
                source_name, source_files = fallback
                for source in source_files:
                    shutil.copyfile(source, out / source.name)
                (out / "LICENSE_TEXT_SOURCE.txt").write_text(
                    f"Package: {pkg['name']} {pkg['version']}\n"
                    f"SPDX license: {pkg.get('license') or 'UNKNOWN'}\n"
                    f"License text source: {source_name}\n"
                    f"Repository: {pkg.get('repository') or 'n/a'}\n",
                    encoding="utf-8",
                )
            else:
                stubs.append(pkg["name"])
                (out / "MISSING_LICENSE_FILE.txt").write_text(
                    f"{pkg['name']} {pkg['version']}\n"
                    f"License: {pkg.get('license') or 'UNKNOWN'}\n"
                    f"Repository: {pkg.get('repository') or 'n/a'}\n"
                    "No matching SPDX license text was found in the workspace dependency graph.\n",
                    encoding="utf-8",
                )
    print(f"bundled licenses for {len(seen - members)} crates into {dest}", file=sys.stderr)
    if stubs:
        sys.exit(f"No license text found for: {', '.join(stubs)}")
